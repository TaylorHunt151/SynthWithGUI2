//This loop is called by the audio device once per buffer. It generates audio data in batches and writes it to the buffer.
int audioLoop(void* outputBuffer, void* inputBuffer, unsigned int nBufferFrames,
    double streamTime, RtAudioStreamStatus status, void* userData)
{
    double* buffer = (double*)outputBuffer;
    double* lastValues = (double*)userData;

    if (status)
        wxLogMessage("System Underflow Detected");
    for (int i = 0; i < nBufferFrames; i++) {
        for (int j = 0; j < channelCount; j++) {
            buffer[i * channelCount + j] = 0;
        }
    }

    for (int i = 0; i < 2; i++) {
        LFOs[i].lfoGen();
    }

    for (int i = 0; i < voiceCount; i++) {

        voices[i].setVars();

        voices[i].oscillator(nBufferFrames, channelCount); //This is where the oscillator method is called.
        voices[i].oscillator2(nBufferFrames, channelCount);
        //The buffer is filled with the audio data generated by the oscillator. The phase is updated by the oscillator method and returned to the main loop.

        voices[i].biquadCoefs(sampRate); //Sets the coefficients used to calculate the filter output
        voices[i].biquadFilter();

        voices[i].envelope(nBufferFrames, channelCount, sampRate);
        for (int j = 0; j < nBufferFrames * channelCount; j++) { //adds together all the different voices' outputs
            buffer[j] += voices[i].localBuff[j];
        }

    }
    //flanger->flanger(buffer);
    //chorus->chorus(buffer);
    //dly->delay(buffer);
    goodverb->reverb(buffer);
    //distortion->distort(buffer);


    return 0;

}

class AudioManager {
public:
    AudioManager() : running(false) {}

    void start() {//Starts the audio on a separate thread so 

        audioThread = std::thread(&AudioManager::audioStart, this);
        audioThread.detach();
    }

    void stop() {
        running = false;
        if (audioThread.joinable()) {
            audioThread.join();
        }
    }

private:
    void audioStart() { //Initializes the audio device.

        RtAudio dac;
        std::vector<unsigned int> deviceIds = dac.getDeviceIds();
        if (deviceIds.size() < 1) {
            wxLogMessage("No audio devices found!");
            return;
        }

        RtAudio::StreamParameters parameters;
        parameters.deviceId = dac.getDefaultOutputDevice(); //Set the device ID to the default output device
        parameters.nChannels = channelCount; //Set the number of channels to 2 (left and right channel for stereo)
        parameters.firstChannel = 0;
        unsigned int sampleRate = sampRate; //Standard CD quality sample rate
        unsigned int bufferFrames = bufferSize; //The number of sample frames. Make this higher for less CPU usage, or lower for less latency. This should be changable by the user in the final version. Also, it should be a power of two.
        double data[2] = { 0, 0 }; //IDK what this does but it was in the example code for the library i downloaded so I'm keeping it for now. I'll remove it if it turns out to be unnecessary.

        if (dac.openStream(&parameters, NULL, RTAUDIO_FLOAT64, sampleRate,
            &bufferFrames, &audioLoop, (void*)&data)) {
            return; //Checks for a problem with device settings
        }

        //Once the stream is opened, this starts the stream
        if (dac.startStream()) {
            return;
        }

        running = true;
        while (running) {
            std::this_thread::sleep_for(std::chrono::milliseconds(100));
        }

        //Stops the audio stream
        if (dac.isStreamRunning())
            dac.stopStream();

        if (dac.isStreamOpen()) dac.closeStream();

    }

    std::thread audioThread; //Create a new thread to run the audio independent of the GUI
    std::atomic<bool> running; //DON'T ADD A UI ELEMENT FOR THIS. This value is used to stop the audio thread when the program closes. Since the stop() function is called by the App class destructor, it is declared as an atomic to avoic race conditions. DON'T ADD A UI ELEMENT FOR THIS
};


class KnobControl : public wxPanel {
public:
    KnobControl(wxWindow* parent, wxWindowID id = wxID_ANY, int minValue = 0, int maxValue = 100)
        : wxPanel(parent, id, wxDefaultPosition, wxSize(60, 60), wxBORDER_SIMPLE),
        minValue(minValue), maxValue(maxValue), value((minValue + maxValue) / 2), angle(0), varToChange(varToChange){

        SetBackgroundStyle(wxBG_STYLE_PAINT); //Avoid flickering
        Bind(wxEVT_PAINT, &KnobControl::OnPaint, this);
        Bind(wxEVT_LEFT_DOWN, &KnobControl::OnMouseDown, this);
        Bind(wxEVT_MOTION, &KnobControl::OnMouseMove, this);
        Bind(wxEVT_LEFT_UP, &KnobControl::OnMouseUp, this);
    }

    int GetValue() const { return value; }
    void SetValue(int newValue) {
        if (newValue < minValue) newValue = minValue;
        if (newValue > maxValue) newValue = maxValue;
        value = newValue;
        angle = (value - minValue) * 270.0 / (maxValue - minValue) - 135; //Map value to angle (-135° to 135°)
        Refresh();
    }

private:
    int minValue, maxValue, value, xPrevious, yPrevious;
    float& varToChange;
    double angle = 0;
    bool isDragging = false;


    void OnPaint(wxPaintEvent&) {
        wxAutoBufferedPaintDC dc(this);
        dc.Clear();
        dc.SetBrush(*wxLIGHT_GREY_BRUSH);
        dc.DrawCircle(30, 30, 20); //Draw the knob background

        //Draw indicator line based on angle
        double radians = angle * M_PI / 180.0;
        int x = 30 + 15 * cos(radians);
        int y = 30 - 15 * sin(radians);
        dc.SetPen(wxPen(*wxBLACK, 2));
        dc.DrawLine(30, 30, x, y);
    }

    void OnMouseDown(wxMouseEvent& event) {
        wxPoint pos = event.GetPosition();
        xPrevious = pos.x;
        yPrevious = pos.y;
        isDragging = true;
        CaptureMouse();
    }

    void OnMouseMove(wxMouseEvent& event) {
        if (isDragging) {
            wxPoint pos = event.GetPosition();

            // Calculate the delta based on mouse movement.
            int delta = ((pos.y - yPrevious) - (pos.x - xPrevious));

            // Compute a temporary new angle.
            double newAngle = angle + delta;

            // Clamp the newAngle to the allowed range [ -135, 135 ].
            if (newAngle > 135)
                newAngle = 135;
            else if (newAngle < -135)
                newAngle = -135;

            // Only update the angle if it hasn't hit the boundary or if the delta
            // would move it back within the range.
            angle = newAngle;

            // Update previous mouse positions.
            xPrevious = pos.x;
            yPrevious = pos.y;

            // Map the clamped angle to the knob value.
            value = minValue + (angle + 135) * (maxValue - minValue) / 270;

            Refresh();
        }
    }

    void OnMouseUp(wxMouseEvent&) {
        if (isDragging) {
            isDragging = false;
            ReleaseMouse();
        }
    }
};


extern KeyInputManager* keyInputManager;

// This custom control draws 16 keys (A to P) and uses the KeyInputManager for key states.
class PianoKeyboard : public wxPanel {
public:
    PianoKeyboard(wxWindow* parent, wxWindowID id = wxID_ANY)
        : wxPanel(parent, id, wxDefaultPosition, wxSize(600, 100))
    {
        // Use double-buffered painting to reduce flicker.
        SetBackgroundStyle(wxBG_STYLE_PAINT);
        Bind(wxEVT_PAINT, &PianoKeyboard::OnPaint, this);
    }

private:
    // In OnPaint we directly query keyInputManager->noteSet which should have size at least 16.
    void OnPaint(wxPaintEvent&) {
        wxAutoBufferedPaintDC dc(this);
        dc.Clear();

        int numKeys = 16; // We display keys A to P.
        wxSize sz = GetSize();
        int keyWidth = sz.GetWidth() / numKeys;
        int keyHeight = sz.GetHeight();

        // Access the global keyInputManager noteSet.
        // (Ensure that keyInputManager is properly instantiated elsewhere.)
        std::vector<char> noteSet = keyInputManager->noteSet;

        for (int i = 0; i < numKeys; i++) {
            wxRect rect(i * keyWidth, 0, keyWidth, keyHeight);

            // Determine if this key is "pressed". If the noteSet at this index is not blank (' '), treat it as pressed.
            bool pressed = (i < static_cast<int>(noteSet.size()) && noteSet[i] != ' ');

            // Set brush color based on pressed state.
            dc.SetBrush(pressed ? *wxBLUE_BRUSH : *wxWHITE_BRUSH);
            dc.SetPen(*wxBLACK_PEN);
            dc.DrawRectangle(rect);

            // Label: If pressed, use the actual key from noteSet; otherwise default to the letter (A + i)
            wxString label;
            if (pressed)
                label.Printf("%c", noteSet[i]);
            else
                label.Printf("%c", 'A' + i);

            wxSize textSize = dc.GetTextExtent(label);
            dc.DrawText(label,
                rect.x + (keyWidth - textSize.GetWidth()) / 2,
                rect.y + (keyHeight - textSize.GetHeight()) / 2);
        }
    }
};

